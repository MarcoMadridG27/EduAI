      whatsappPromoTitle: "Can't find what you are looking for in the repository?",
      whatsappPromoSubtitle: "Generate your custom lesson plan instantly by chatting with our AI bot on WhatsApp at ",
      whatsappPromoCTA: "Chat with Bot",
      popularDocs: "Popular Documents",
      readDoc: "Read document",
