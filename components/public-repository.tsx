      heroSubtitle: "Waranqantin yachachiqkunapa rurasqan yachachiykunata riqsiy. Yachachinaykipaq listo.",
      whatsappPromoTitle: "¿Manachu repositorio nisqapi maskasqaykita tarinki?",
      whatsappPromoSubtitle: "Tupachisqa yachachiyta IA bot nisqawan chateaspa WhatsApp nisqapi ruray: ",
